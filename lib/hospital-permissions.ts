export function getPermissionsForRole(role: HospitalRole) {
  return hospitalPermissionsByRole[role] ?? [];
}

export function resolveHospitalPermissions(role: HospitalRole, storedPermissions?: string[] | null) {
  const roleDefaults = getPermissionsForRole(role);
  if (!storedPermissions?.length) return roleDefaults;
  return [...new Set([...roleDefaults, ...storedPermissions])];
}
